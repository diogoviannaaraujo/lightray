/// Mac virtual key codes (`kVK_*`, Carbon's HIToolbox/Events.h) and USB HID usages on the
/// keyboard page (0x07), in both directions. The client sends usages; the host posts key codes.
public enum KeyMap {
    /// `(kVK, HID usage)`.
    static let pairs: [(UInt16, UInt16)] = [
        // Letters.
        (0x00, 0x04), (0x0B, 0x05), (0x08, 0x06), (0x02, 0x07), (0x0E, 0x08), (0x03, 0x09), (0x05, 0x0A),
        (0x04, 0x0B), (0x22, 0x0C), (0x26, 0x0D), (0x28, 0x0E), (0x25, 0x0F), (0x2E, 0x10), (0x2D, 0x11),
        (0x1F, 0x12), (0x23, 0x13), (0x0C, 0x14), (0x0F, 0x15), (0x01, 0x16), (0x11, 0x17), (0x20, 0x18),
        (0x09, 0x19), (0x0D, 0x1A), (0x07, 0x1B), (0x10, 0x1C), (0x06, 0x1D),
        // Digits 1–9, 0.
        (0x12, 0x1E), (0x13, 0x1F), (0x14, 0x20), (0x15, 0x21), (0x17, 0x22), (0x16, 0x23), (0x1A, 0x24),
        (0x1C, 0x25), (0x19, 0x26), (0x1D, 0x27),
        // Return, Escape, Delete (backspace), Tab, Space.
        (0x24, 0x28), (0x35, 0x29), (0x33, 0x2A), (0x30, 0x2B), (0x31, 0x2C),
        // - = [ ] \ ; ' ` , . /
        (0x1B, 0x2D), (0x18, 0x2E), (0x21, 0x2F), (0x1E, 0x30), (0x2A, 0x31), (0x29, 0x33), (0x27, 0x34),
        (0x32, 0x35), (0x2B, 0x36), (0x2F, 0x37), (0x2C, 0x38),
        // Caps Lock.
        (0x39, 0x39),
        // F1–F12.
        (0x7A, 0x3A), (0x78, 0x3B), (0x63, 0x3C), (0x76, 0x3D), (0x60, 0x3E), (0x61, 0x3F), (0x62, 0x40),
        (0x64, 0x41), (0x65, 0x42), (0x6D, 0x43), (0x67, 0x44), (0x6F, 0x45),
        // Help (Insert), Home, Page Up, Forward Delete, End, Page Down, arrows.
        (0x72, 0x49), (0x73, 0x4A), (0x74, 0x4B), (0x75, 0x4C), (0x77, 0x4D), (0x79, 0x4E),
        (0x7C, 0x4F), (0x7B, 0x50), (0x7D, 0x51), (0x7E, 0x52),
        // Keypad: Clear, / * - + Enter, 1–9, 0, ., =.
        (0x47, 0x53), (0x4B, 0x54), (0x43, 0x55), (0x4E, 0x56), (0x45, 0x57), (0x4C, 0x58),
        (0x53, 0x59), (0x54, 0x5A), (0x55, 0x5B), (0x56, 0x5C), (0x57, 0x5D), (0x58, 0x5E), (0x59, 0x5F),
        (0x5B, 0x60), (0x5C, 0x61), (0x52, 0x62), (0x41, 0x63), (0x51, 0x67),
        // ISO section key, PC application (menu) key.
        (0x0A, 0x64), (0x6E, 0x65),
        // F13–F20.
        (0x69, 0x68), (0x6B, 0x69), (0x71, 0x6A), (0x6A, 0x6B), (0x40, 0x6C), (0x4F, 0x6D), (0x50, 0x6E),
        (0x5A, 0x6F),
        // Mute, Volume Up, Volume Down.
        (0x4A, 0x7F), (0x48, 0x80), (0x49, 0x81),
        // JIS: keypad comma, underscore (International1), yen (International3), kana, eisu.
        (0x5F, 0x85), (0x5E, 0x87), (0x5D, 0x89), (0x68, 0x90), (0x66, 0x91),
        // Modifiers: left Control, Shift, Option, Command; right Control, Shift, Option, Command.
        (0x3B, 0xE0), (0x38, 0xE1), (0x3A, 0xE2), (0x37, 0xE3), (0x3E, 0xE4), (0x3C, 0xE5), (0x3D, 0xE6),
        (0x36, 0xE7),
    ]

    static let usageByKeyCode = Dictionary(uniqueKeysWithValues: pairs)
    static let keyCodeByUsage = Dictionary(uniqueKeysWithValues: pairs.map { ($1, $0) })

    public static func usage(forKeyCode code: UInt16) -> UInt16? { usageByKeyCode[code] }
    public static func keyCode(forUsage usage: UInt16) -> UInt16? { keyCodeByUsage[usage] }

    public enum Modifier: CaseIterable, Sendable {
        case leftControl, leftShift, leftOption, leftCommand, rightControl, rightShift, rightOption, rightCommand
    }

    public static func modifier(forUsage usage: UInt16) -> Modifier? {
        switch usage {
        case 0xE0: .leftControl
        case 0xE1: .leftShift
        case 0xE2: .leftOption
        case 0xE3: .leftCommand
        case 0xE4: .rightControl
        case 0xE5: .rightShift
        case 0xE6: .rightOption
        case 0xE7: .rightCommand
        default: nil
        }
    }

    public static let capsLockUsage: UInt16 = 0x39

    /// The device-dependent bit in an event's modifier flags that says this side's key is down
    /// (IOLLEvent.h `NX_DEVICE*KEYMASK`).
    public static func deviceMask(_ modifier: Modifier) -> UInt64 {
        switch modifier {
        case .leftControl: 0x0001
        case .leftShift: 0x0002
        case .rightShift: 0x0004
        case .leftCommand: 0x0008
        case .rightCommand: 0x0010
        case .leftOption: 0x0020
        case .rightOption: 0x0040
        case .rightControl: 0x2000
        }
    }

    /// The device-independent flag (`NSEvent.ModifierFlags` / `CGEventFlags`).
    public static func flag(_ modifier: Modifier) -> UInt64 {
        switch modifier {
        case .leftShift, .rightShift: 1 << 17
        case .leftControl, .rightControl: 1 << 18
        case .leftOption, .rightOption: 1 << 19
        case .leftCommand, .rightCommand: 1 << 20
        }
    }

    /// Keys a Mac keyboard reports with the numeric-pad flag: the keypad and the arrows.
    public static func isNumericPad(_ usage: UInt16) -> Bool { (0x53...0x63).contains(usage) || usage == 0x67 || (0x4F...0x52).contains(usage) }

    /// Keys a Mac keyboard reports with the function flag: the navigation cluster and F-keys.
    public static func isFunctionCluster(_ usage: UInt16) -> Bool {
        (0x3A...0x45).contains(usage) || (0x49...0x52).contains(usage) || (0x68...0x6F).contains(usage)
    }
}
